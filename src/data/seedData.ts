function resolveStudioPhotos(raw: RawSeedProduct): [string, string] {
  const exact = PRODUCT_SPECIFIC_PHOTOS[raw.id];
  if (exact) return exact;

  switch (raw.archetype) {
    case 'case':
      return [STUDIO_PHOTO_URLS.siliconeCase, STUDIO_PHOTO_URLS.magsafeDock];
    case 'charger':
    case 'stand':
      return [STUDIO_PHOTO_URLS.magsafeDock, STUDIO_PHOTO_URLS.kevlarCable];
    case 'cable':
      return [STUDIO_PHOTO_URLS.kevlarCable, STUDIO_PHOTO_URLS.magsafeDock];
    case 'powerbank':
    case 'watchband':
      return [STUDIO_PHOTO_URLS.magneticCarMount, STUDIO_PHOTO_URLS.magsafeDock];
    case 'audio':
      return [STUDIO_PHOTO_URLS.ancEarbuds, STUDIO_PHOTO_URLS.magsafeDock];
    case 'robot':
      return [STUDIO_PHOTO_URLS.stemRobot, STUDIO_PHOTO_URLS.stemKit];
    case 'drone':
      return [STUDIO_PHOTO_URLS.kidsDrone, STUDIO_PHOTO_URLS.stemRobot];
    case 'stemkit':
      return [STUDIO_PHOTO_URLS.stemKit, STUDIO_PHOTO_URLS.smartCubes];
    case 'cube':
      return [STUDIO_PHOTO_URLS.smartCubes, STUDIO_PHOTO_URLS.stemKit];
    case 'lamp':
      return [STUDIO_PHOTO_URLS.rgbAmbientLamp, STUDIO_PHOTO_URLS.geometricDecor];
    case 'diffuser':
      return [STUDIO_PHOTO_URLS.luxuryFragranceGift, STUDIO_PHOTO_URLS.velvetGiftBox];
    case 'desk':
      return [STUDIO_PHOTO_URLS.velvetGiftBox, STUDIO_PHOTO_URLS.geometricDecor];
    case 'clock':
    case 'pen':
    default:
      return [STUDIO_PHOTO_URLS.geometricDecor, STUDIO_PHOTO_URLS.luxuryFragranceGift];
  }
}

